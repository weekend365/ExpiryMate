/* global require, __dirname, Buffer, console, process */
const path = require('node:path');
const fs = require('node:fs');
const sharp = require('../../../node_modules/.pnpm/sharp@0.34.5/node_modules/sharp');

(async () => {
  const selection = JSON.parse(fs.readFileSync(path.join(__dirname, 'selected-artwork.json'), 'utf8'));
  const width = 360;
  const height = 640;
  const gutter = 24;
  const rowHeight = 684;
  const canvasWidth = gutter + 4 * (width + gutter);
  const layers = [];
  const measurements = [];
  fs.mkdirSync(path.join(__dirname, 'review'), { recursive: true });
  for (const scene of selection) {
    const i = scene.scene - 1;
    const number = String(scene.scene).padStart(2, '0');
    const source = path.resolve(__dirname, '../../..', scene.file);
    const metadata = await sharp(source).metadata();
    const preview = path.join(__dirname, 'review', `${number}-360.png`);
    await sharp(source)
      .resize(width, height, { fit: 'contain', background: '#f6f2e9' })
      .png().toFile(preview);
    const column = i < 4 ? i : i - 4;
    const row = i < 4 ? 0 : 1;
    const x = gutter + column * (width + gutter) + (row ? (width + gutter) / 2 : 0);
    const y = 56 + row * rowHeight;
    layers.push({ input: preview, left: x, top: y });
    layers.push({
      input: Buffer.from(`<svg width="360" height="30"><text x="0" y="23" font-family="Arial,sans-serif" font-size="20" fill="#38453e">${number}</text></svg>`),
      left: x,
      top: y - 32,
    });
    measurements.push({
      scene: scene.scene,
      candidate: scene.candidate,
      source: scene.file,
      sourceSize: [metadata.width, metadata.height],
      sourceAspectRatio: metadata.width / metadata.height,
      deltaFrom9by16Percent: Math.abs(metadata.width / metadata.height / (9 / 16) - 1) * 100,
      preview: `review/${number}-360.png`,
      previewSize: [width, height],
      sourceProcessing: 'none; raw generated bytes retained',
      previewProcessing: 'uniform contain resize; no artwork retouching or nonuniform stretching',
    });
  }
  await sharp({ create: { width: canvasWidth, height: 56 + rowHeight + height + gutter, channels: 3, background: '#f6f2e9' } })
    .composite(layers).jpeg({ quality: 94 }).toFile(path.join(__dirname, 'review', 'overview.jpg'));
  fs.writeFileSync(path.join(__dirname, 'review', 'image-dimensions.json'), JSON.stringify(measurements, null, 2) + '\n');
  console.log('Saved seven 360x640 previews and numbered two-row overview; source artwork bytes unchanged.');
})().catch(error => { console.error(error); process.exit(1); });
