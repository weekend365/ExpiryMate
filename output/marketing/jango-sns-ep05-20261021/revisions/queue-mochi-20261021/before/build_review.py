"""Build review-only thumbnails and records; preserve generated scene bytes."""
from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
import hashlib
import html
import json
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[2]
REVIEW = OUT / "review"
REVIEW.mkdir(exist_ok=True)
SELECTED = ["scene-01-r1", "scene-02-r3", "scene-03-r2", "scene-04-r1", "scene-05-r1"]
TITLES = ["장고가 이상하게 빠르다", "수상한 시간 확인", "목적지 공개", "오픈런의 정체", "함께 먹는 마무리"]
ALTS = [
    "가을 낙엽이 쌓인 골목에서 작은 냉장고 캐릭터 장고가 앞서 달리고, 아이보리 운동복과 초록 바지를 입은 여성이 놀라 따라옵니다.",
    "골목 모퉁이에서 장고가 오른손목의 시계를 확인하며 둥근 장갑 전체로 진행 방향을 가리킵니다. 뒤의 여성은 한 손을 들어 기다려 달라는 몸짓을 합니다.",
    "민트색 줄무늬 차양과 따뜻한 진열창이 있는 빵집 앞에 도착합니다. 여성이 몸을 숙여 바라보고, 장고는 신난 표정을 짓습니다. 창문 표지는 글자를 넣기 위해 비워 두었습니다.",
    "빵 세 개가 담긴 종이봉투를 안고 기뻐하는 장고 옆에서 여성이 무릎에 손을 짚고 바라봅니다. 같은 빵집의 문이 열려 있습니다.",
    "여성이 장고 옆에 쪼그려 앉아 빵 한 개를 들고 웃습니다. 장고는 두 개가 남은 빵 봉투를 안고 기뻐합니다."
]
def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()
def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")

episode = json.loads((OUT / "episode.json").read_text())
episode["status"] = "source-art-created-awaiting-user-review"
episode["continuity"]["intentionalChanges"] = [
    "woman in ivory zip running jacket, forest-green joggers and ivory shoes",
    "autumn neighborhood path and unbranded bakery",
    "small round watch at Jango's anatomical right mitten cuff in final selected scenes; initial left-cuff plan superseded during visual continuity correction",
    "new sprint, urgent watch check, bakery discovery and sharing-food expressions"
]
episode["resolvedArtChoices"] = [
    "Five distinct original scenes are provided, including a newly illustrated sharing-bread closing scene.",
    "The opening-hours placard is on the central display window, left of the door, for later safe lettering.",
    "The bakery food is rendered as three small golden round bread rolls; one moves to the woman's hand in the closing scene.",
    "All dialogue, opening-hours text and brand/question copy remain separate from raw artwork."
]
write_json(OUT / "episode.json", episode)

entries = []
font_path = ROOT / "design/jango/emoticons/kakao-32/v18/fonts/Gaegu-Bold.ttf"
font = ImageFont.truetype(str(font_path), 28)
heading_font = ImageFont.truetype(str(font_path), 44)
small_font = ImageFont.truetype(str(font_path), 24)
overview = Image.new("RGB", (1912, 826), "#f7f1e5")
draw = ImageDraw.Draw(overview)
draw.text((24, 16), "장고랑 살아보니 05  ·  원화 검토본", font=heading_font, fill="#293f37")
for i, candidate in enumerate(SELECTED):
    path = OUT / "source-art" / f"{candidate}.png"
    with Image.open(path) as image:
        image.load()
        width, height = image.size
        thumb_height = round(height * 360 / width)
        thumb = image.convert("RGB").resize((360, thumb_height), Image.Resampling.LANCZOS)
        thumb_path = REVIEW / f"{i+1:02d}-360.png"
        thumb.save(thumb_path)
        x = 24 + i * 376
        overview.paste(thumb, (x, 90))
        draw.text((x, 742), f"{i+1:02d}  {TITLES[i]}", font=font, fill="#293f37")
        timing = episode["scenes"][i]
        draw.text((x, 780), f'{timing["start"]}~{timing["end"]}초 예정', font=small_font, fill="#59665f")
        entries.append({
            "scene": i+1, "candidate": candidate,
            "file": str(path.relative_to(ROOT)), "sha256": digest(path),
            "width": width, "height": height, "nativeAspectRatio": width/height,
            "preview": str(thumb_path.relative_to(OUT)), "previewSize": [360, thumb_height],
            "previewMethod": "Uniform width scaling with integer rounding only; no art editing, crop or added lettering on individual previews.",
            "alt": ALTS[i]
        })
overview.save(REVIEW / "overview.jpg", quality=94, subsampling=0)
write_json(OUT / "selected-artwork.json", {
    "status": "source-art-candidates-ready-for-user-review",
    "selection": entries,
    "unselectedAttempts": ["source-art/scene-02-r1.png", "source-art/scene-02-r2.png", "source-art/scene-03-r1.png"],
    "unselectedRetention": "Exact edit inputs retained for lineage and before/after evidence, not final selections.",
    "overview": "review/overview.jpg",
    "approval": "User authorized storyboard-based image production; newly generated bytes have not yet been user-adopted.",
    "sourceMethod": "official built-in imagegen; no fallback CLI/API and no scene painting by code",
    "rawDimensions": "941x1672 native generation, approximately 9:16; intended later Reel delivery 1080x1920 has not been rendered."
})
write_json(OUT / "alt-text.json", [{"scene": i+1, "text": text} for i,text in enumerate(ALTS)])

cards = []
for i, entry in enumerate(entries):
    scene = episode["scenes"][i]
    dialogue = " / ".join(f'{d["speaker"]}: “{d["text"]}”' for d in scene["dialogue"]) or "너는 러닝파, 오픈런파?"
    cards.append(
        f'<article><h2>{i+1:02d} · {html.escape(TITLES[i])}</h2>'
        f'<p class="timing">{scene["start"]}~{scene["end"]}초 예정</p>'
        f'<a href="../source-art/{entry["candidate"]}.png"><img src="{i+1:02d}-360.png" width="360" height="640" alt="{html.escape(entry["alt"])}"></a>'
        f'<p>{html.escape(dialogue)}</p><a class="download" href="../source-art/{entry["candidate"]}.png" download>원화 PNG 열기</a></article>'
    )
page = """<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>장고랑 살아보니 05 · 원화 검토본</title>
<style>body{margin:0;background:#f7f1e5;color:#293f37;font-family:-apple-system,BlinkMacSystemFont,"Apple SD Gothic Neo",sans-serif;line-height:1.6}main{max-width:1920px;margin:auto;padding:32px 24px}h1{font-size:28px;margin:0 0 8px}header p{max-width:850px}.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(260px,1fr));gap:20px;margin-top:28px}article{min-width:0;background:#fffaf2;border:1px solid #dbe3d6;border-radius:16px;padding:16px}h2{font-size:18px;margin:0}.timing{font-size:13px;color:#66756c;margin:4px 0 14px}img{display:block;width:100%;height:auto;aspect-ratio:9/16;object-fit:contain;border-radius:8px}a{color:#24745e}.download{font-weight:600}footer{margin:32px 0 8px;color:#59665f;font-size:14px}</style>
<main><header><h1>장고랑 살아보니 05 — 러닝인 줄 알았는데 오픈런</h1>
<p>세로 원화 5장 검토본입니다. 대사·말풍선·운영시간 표지·브랜드 문구는 영상 단계에서 별도로 조판합니다. 아래 대사는 장면 맥락을 확인하기 위한 설명입니다.</p>
<p><a href="overview.jpg">다섯 장 한눈에 보기</a> · <a href="../selected-artwork.json">선택 파일 기록</a> · <a href="../prompts/">생성·수정 프롬프트</a></p></header><section class="grid">""" + "".join(cards) + """</section>
<footer>공식 imagegen으로 제작한 AI 작화입니다. 생성 원본 941×1672px를 보존했으며, 개별 미리보기만 폭 360px로 축소했습니다. 원화 검토 단계로, 영상·음악·한글 조판·게시 검수는 후속 단계입니다.</footer></main></html>"""
(REVIEW / "index.html").write_text(page)
print(json.dumps({"selected":len(entries),"nativeSize":[941,1672],"previewSize":[360,640],"overview":"review/overview.jpg","viewer":"review/index.html"},ensure_ascii=False))
